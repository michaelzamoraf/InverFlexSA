namespace APIInverFlexSA.Domain.Entities
{
    /// -----------------------------------------------------------------------------------------------------------
    /// <summary>
    /// Alerta configurada para vigilar el precio de un instrumento.
    /// </summary>
    /// -----------------------------------------------------------------------------------------------------------
    public class PriceAlert
    {
        /// -----------------------------------------------------------------------------------------------------------
        /// <summary>
        /// Identificador de la alerta.
        /// </summary>
        /// -----------------------------------------------------------------------------------------------------------
        public Guid Id { get; set; }

        /// -----------------------------------------------------------------------------------------------------------
        /// <summary>
        /// Cliente propietario.
        /// </summary>
        /// -----------------------------------------------------------------------------------------------------------
        public Guid ClientId { get; set; }

        /// -----------------------------------------------------------------------------------------------------------
        /// <summary>
        /// Instrumento vigilado.
        /// </summary>
        /// -----------------------------------------------------------------------------------------------------------
        public Guid InstrumentId { get; set; }

        /// -----------------------------------------------------------------------------------------------------------
        /// <summary>
        /// Detalle del instrumento.
        /// </summary>
        /// -----------------------------------------------------------------------------------------------------------
        public Instrument Instrument { get; set; } = null!;

        /// -----------------------------------------------------------------------------------------------------------
        /// <summary>
        /// Condición que activa la alerta.
        /// </summary>
        /// -----------------------------------------------------------------------------------------------------------
        public AlertCondition Condition { get; set; }

        /// -----------------------------------------------------------------------------------------------------------
        /// <summary>
        /// Precio usado como referencia.
        /// </summary>
        /// -----------------------------------------------------------------------------------------------------------
        public decimal ReferencePrice { get; set; }

        /// -----------------------------------------------------------------------------------------------------------
        /// <summary>
        /// Umbral de activación, porcentual o absoluto según la condición.
        /// </summary>
        /// -----------------------------------------------------------------------------------------------------------
        public decimal ThresholdValue { get; set; } // Ej: 5.0 para +5%

        /// -----------------------------------------------------------------------------------------------------------
        /// <summary>
        /// Indica si la alerta ya se ha activado.
        /// </summary>
        /// -----------------------------------------------------------------------------------------------------------
        public bool IsTriggered { get; set; } = false;

        /// -----------------------------------------------------------------------------------------------------------
        /// <summary>
        /// Fecha de creación en UTC.
        /// </summary>
        /// -----------------------------------------------------------------------------------------------------------
        public DateTime CreatedAt { get; set; } = DateTime.UtcNow;

        /// -----------------------------------------------------------------------------------------------------------
        /// <summary>
        /// Fecha de activación, si ya ocurrió.
        /// </summary>
        /// -----------------------------------------------------------------------------------------------------------
        public DateTime? TriggeredAt { get; set; }
    }
}
