namespace APIInverFlexSA.Domain.Entities;

/// -----------------------------------------------------------------------------------------------------------
/// <summary>
/// Notificación persistida que informa al cliente que una alerta de precio se activó.
/// </summary>
/// -----------------------------------------------------------------------------------------------------------
public sealed class PriceAlertNotification
{
    /// -----------------------------------------------------------------------------------------------------------
    /// <summary>
    /// Identificador de la notificación.
    /// </summary>
    /// -----------------------------------------------------------------------------------------------------------
    public Guid Id { get; set; } = Guid.NewGuid();

    /// -----------------------------------------------------------------------------------------------------------
    /// <summary>
    /// Cliente destinatario.
    /// </summary>
    /// -----------------------------------------------------------------------------------------------------------
    public Guid ClientId { get; set; }

    /// -----------------------------------------------------------------------------------------------------------
    /// <summary>
    /// Alerta que originó la notificación.
    /// </summary>
    /// -----------------------------------------------------------------------------------------------------------
    public Guid PriceAlertId { get; set; }

    /// -----------------------------------------------------------------------------------------------------------
    /// <summary>
    /// Relación con la alerta.
    /// </summary>
    /// -----------------------------------------------------------------------------------------------------------
    public PriceAlert PriceAlert { get; set; } = null!;

    /// -----------------------------------------------------------------------------------------------------------
    /// <summary>
    /// Mensaje legible para el cliente.
    /// </summary>
    /// -----------------------------------------------------------------------------------------------------------
    public string Message { get; set; } = string.Empty;

    /// -----------------------------------------------------------------------------------------------------------
    /// <summary>
    /// Precio observado cuando se activó la alerta.
    /// </summary>
    /// -----------------------------------------------------------------------------------------------------------
    public decimal TriggerPrice { get; set; }

    /// -----------------------------------------------------------------------------------------------------------
    /// <summary>
    /// Fecha de creación UTC.
    /// </summary>
    /// -----------------------------------------------------------------------------------------------------------
    public DateTime CreatedAt { get; set; } = DateTime.UtcNow;

    /// -----------------------------------------------------------------------------------------------------------
    /// <summary>
    /// Indica si el cliente ya consultó la notificación.
    /// </summary>
    /// -----------------------------------------------------------------------------------------------------------
    public bool IsRead { get; set; }
}
