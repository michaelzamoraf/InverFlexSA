namespace APIInverFlexSA.Domain.Entities
{
    /// -----------------------------------------------------------------------------------------------------------
    /// <summary>
    /// Instrumento financiero negociable.
    /// </summary>
    /// -----------------------------------------------------------------------------------------------------------
    public class Instrument
    {
        /// -----------------------------------------------------------------------------------------------------------
        /// <summary>
        /// Identificador único.
        /// </summary>
        /// -----------------------------------------------------------------------------------------------------------
        public Guid Id { get; set; }

        /// -----------------------------------------------------------------------------------------------------------
        /// <summary>
        /// Código de cotización.
        /// </summary>
        /// -----------------------------------------------------------------------------------------------------------
        public string Ticker { get; set; } = string.Empty;

        /// -----------------------------------------------------------------------------------------------------------
        /// <summary>
        /// Nombre comercial.
        /// </summary>
        /// -----------------------------------------------------------------------------------------------------------
        public string Name { get; set; } = string.Empty;

        /// -----------------------------------------------------------------------------------------------------------
        /// <summary>
        /// Categoría del instrumento.
        /// </summary>
        /// -----------------------------------------------------------------------------------------------------------
        public InstrumentCategory Category { get; set; }

        /// -----------------------------------------------------------------------------------------------------------
        /// <summary>
        /// Sector económico.
        /// </summary>
        /// -----------------------------------------------------------------------------------------------------------
        public string Sector { get; set; } = string.Empty;

        /// -----------------------------------------------------------------------------------------------------------
        /// <summary>
        /// Precio de referencia inicial.
        /// </summary>
        /// -----------------------------------------------------------------------------------------------------------
        public decimal BasePrice { get; set; }

        /// -----------------------------------------------------------------------------------------------------------
        /// <summary>
        /// Indica si se puede operar con el instrumento.
        /// </summary>
        /// -----------------------------------------------------------------------------------------------------------
        public bool IsActive { get; set; } = true;
    }
}
