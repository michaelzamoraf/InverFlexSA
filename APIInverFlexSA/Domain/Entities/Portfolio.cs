namespace APIInverFlexSA.Domain.Entities
{
    /// -----------------------------------------------------------------------------------------------------------
    /// <summary>
    /// Cartera de inversión perteneciente a un cliente.
    /// </summary>
    /// -----------------------------------------------------------------------------------------------------------
    public class Portfolio
    {
        /// -----------------------------------------------------------------------------------------------------------
        /// <summary>
        /// Identificador de la cartera.
        /// </summary>
        /// -----------------------------------------------------------------------------------------------------------
        public Guid Id { get; set; }

        /// -----------------------------------------------------------------------------------------------------------
        /// <summary>
        /// Identificador del cliente titular.
        /// </summary>
        /// -----------------------------------------------------------------------------------------------------------
        public Guid ClientId { get; set; }

        /// -----------------------------------------------------------------------------------------------------------
        /// <summary>
        /// Cliente titular.
        /// </summary>
        /// -----------------------------------------------------------------------------------------------------------
        public User Client { get; set; } = null!;

        /// -----------------------------------------------------------------------------------------------------------
        /// <summary>
        /// Efectivo disponible para operar.
        /// </summary>
        /// -----------------------------------------------------------------------------------------------------------
        public decimal AvailableCash { get; set; }

        /// -----------------------------------------------------------------------------------------------------------
        /// <summary>
        /// Última fecha de actualización en UTC.
        /// </summary>
        /// -----------------------------------------------------------------------------------------------------------
        public DateTime UpdatedAt { get; set; } = DateTime.UtcNow;

        /// -----------------------------------------------------------------------------------------------------------
        /// <summary>
        /// Posiciones mantenidas en la cartera.
        /// </summary>
        /// -----------------------------------------------------------------------------------------------------------
        public ICollection<PortfolioPosition> Positions { get; set; } = new List<PortfolioPosition>();
    }
}
