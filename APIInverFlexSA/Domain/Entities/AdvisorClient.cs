namespace APIInverFlexSA.Domain.Entities
{
    /// -----------------------------------------------------------------------------------------------------------
    /// <summary>
    /// Relación de asignación entre un asesor y un cliente.
    /// </summary>
    /// -----------------------------------------------------------------------------------------------------------
    public class AdvisorClient
    {
        /// -----------------------------------------------------------------------------------------------------------
        /// <summary>
        /// Identificador del asesor.
        /// </summary>
        /// -----------------------------------------------------------------------------------------------------------
        public Guid AdvisorId { get; set; }

        /// -----------------------------------------------------------------------------------------------------------
        /// <summary>
        /// Navegación al asesor.
        /// </summary>
        /// -----------------------------------------------------------------------------------------------------------
        public User Advisor { get; set; } = null!;

        /// -----------------------------------------------------------------------------------------------------------
        /// <summary>
        /// Identificador del cliente.
        /// </summary>
        /// -----------------------------------------------------------------------------------------------------------
        public Guid ClientId { get; set; }

        /// -----------------------------------------------------------------------------------------------------------
        /// <summary>
        /// Navegación al cliente.
        /// </summary>
        /// -----------------------------------------------------------------------------------------------------------
        public User Client { get; set; } = null!;

        /// -----------------------------------------------------------------------------------------------------------
        /// <summary>
        /// Fecha de asignación en UTC.
        /// </summary>
        /// -----------------------------------------------------------------------------------------------------------
        public DateTime AssignedAt { get; set; } = DateTime.UtcNow;
    }
}
