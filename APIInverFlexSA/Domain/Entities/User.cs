namespace APIInverFlexSA.Domain.Entities
{
    /// -----------------------------------------------------------------------------------------------------------
    /// <summary>
    /// Usuario de la plataforma, con rol y relaciones de inversión.
    /// </summary>
    /// -----------------------------------------------------------------------------------------------------------
    public class User
    {
        /// -----------------------------------------------------------------------------------------------------------
        /// <summary>
        /// Identificador del usuario.
        /// </summary>
        /// -----------------------------------------------------------------------------------------------------------
        public Guid Id { get; set; }

        /// -----------------------------------------------------------------------------------------------------------
        /// <summary>
        /// Nombre completo.
        /// </summary>
        /// -----------------------------------------------------------------------------------------------------------
        public string FullName { get; set; } = string.Empty;

        /// -----------------------------------------------------------------------------------------------------------
        /// <summary>
        /// Correo electrónico usado para autenticación.
        /// </summary>
        /// -----------------------------------------------------------------------------------------------------------
        public string Email { get; set; } = string.Empty;

        /// -----------------------------------------------------------------------------------------------------------
        /// <summary>
        /// Hash de la contraseña.
        /// </summary>
        /// -----------------------------------------------------------------------------------------------------------
        public string PasswordHash { get; set; } = string.Empty;

        /// -----------------------------------------------------------------------------------------------------------
        /// <summary>
        /// Rol de autorización.
        /// </summary>
        /// -----------------------------------------------------------------------------------------------------------
        public UserRole Role { get; set; }

        /// -----------------------------------------------------------------------------------------------------------
        /// <summary>
        /// Fecha de alta en UTC.
        /// </summary>
        /// -----------------------------------------------------------------------------------------------------------
        public DateTime CreatedAt { get; set; } = DateTime.UtcNow;

        /// -----------------------------------------------------------------------------------------------------------
        /// <summary>
        /// Cartera del usuario cuando actúa como cliente.
        /// </summary>
        /// -----------------------------------------------------------------------------------------------------------
        public Portfolio? Portfolio { get; set; }

        /// -----------------------------------------------------------------------------------------------------------
        /// <summary>
        /// Clientes asignados cuando actúa como asesor.
        /// </summary>
        /// -----------------------------------------------------------------------------------------------------------
        public ICollection<AdvisorClient> AssignedClients { get; set; } = new List<AdvisorClient>();

        /// -----------------------------------------------------------------------------------------------------------
        /// <summary>
        /// Asesores asignados al usuario cuando actúa como cliente.
        /// </summary>
        /// -----------------------------------------------------------------------------------------------------------
        public ICollection<AdvisorClient> AssignedAdvisors { get; set; } = new List<AdvisorClient>();
    }
}
