namespace APIInverFlexSA.Domain.Entities
{
    /// -----------------------------------------------------------------------------------------------------------
    /// <summary>
    /// Condición que puede activar una alerta de precio.
    /// </summary>
    /// -----------------------------------------------------------------------------------------------------------
    public enum AlertCondition
    {
        /// -----------------------------------------------------------------------------------------------------------
        /// <summary>
        /// El precio sube el porcentaje indicado.
        /// </summary>
        /// -----------------------------------------------------------------------------------------------------------
        PorcentajeSubida,

        /// -----------------------------------------------------------------------------------------------------------
        /// <summary>
        /// El precio baja el porcentaje indicado.
        /// </summary>
        /// -----------------------------------------------------------------------------------------------------------
        PorcentajeBajada,

        /// -----------------------------------------------------------------------------------------------------------
        /// <summary>
        /// El precio alcanza un objetivo absoluto.
        /// </summary>
        /// -----------------------------------------------------------------------------------------------------------
        PrecioObjetivo
    }
}
