namespace APIInverFlexSA.Domain.Entities
{
    /// -----------------------------------------------------------------------------------------------------------
    /// <summary>
    /// Posición de un instrumento dentro de una cartera.
    /// </summary>
    /// -----------------------------------------------------------------------------------------------------------
    public class PortfolioPosition
    {
        /// -----------------------------------------------------------------------------------------------------------
        /// <summary>
        /// Identificador de la posición.
        /// </summary>
        /// -----------------------------------------------------------------------------------------------------------
        public Guid Id { get; set; }

        /// -----------------------------------------------------------------------------------------------------------
        /// <summary>
        /// Identificador de la cartera.
        /// </summary>
        /// -----------------------------------------------------------------------------------------------------------
        public Guid PortfolioId { get; set; }

        /// -----------------------------------------------------------------------------------------------------------
        /// <summary>
        /// Cartera propietaria.
        /// </summary>
        /// -----------------------------------------------------------------------------------------------------------
        public Portfolio Portfolio { get; set; } = null!;

        /// -----------------------------------------------------------------------------------------------------------
        /// <summary>
        /// Identificador del instrumento.
        /// </summary>
        /// -----------------------------------------------------------------------------------------------------------
        public Guid InstrumentId { get; set; }
        /// <summary>
        /// Instrumento mantenido.
        /// </summary>
        /// -----------------------------------------------------------------------------------------------------------
        public Instrument Instrument { get; set; } = null!;

        /// -----------------------------------------------------------------------------------------------------------
        /// <summary>
        /// Número de unidades mantenidas.
        /// </summary>
        /// -----------------------------------------------------------------------------------------------------------
        public decimal Quantity { get; set; }

        /// -----------------------------------------------------------------------------------------------------------
        /// <summary>
        /// Precio medio de adquisición.
        /// </summary>
        /// -----------------------------------------------------------------------------------------------------------
        public decimal AverageBuyPrice { get; set; }
    }
}
