using APIInverFlexSA.Domain.Entities;
using Microsoft.EntityFrameworkCore;

namespace APIInverFlexSA.Infrastructure.Persistence
{
    /// -----------------------------------------------------------------------------------------------------------
    /// <summary>
    /// Contrato mínimo del contexto de persistencia para la capa de aplicación.
    /// </summary>
    /// -----------------------------------------------------------------------------------------------------------
    public interface IAppDbContext
    {
        /// -----------------------------------------------------------------------------------------------------------
        /// <summary>
        /// Usuarios persistidos.
        /// </summary>
        /// -----------------------------------------------------------------------------------------------------------
        DbSet<User> Users { get; }

        /// -----------------------------------------------------------------------------------------------------------
        /// <summary>
        /// Asignaciones entre asesores y clientes.
        /// </summary>
        /// -----------------------------------------------------------------------------------------------------------
        DbSet<AdvisorClient> AdvisorClients { get; }

        /// -----------------------------------------------------------------------------------------------------------
        /// <summary>
        /// Instrumentos disponibles.
        /// </summary>
        /// -----------------------------------------------------------------------------------------------------------
        DbSet<Instrument> Instruments { get; }

        /// -----------------------------------------------------------------------------------------------------------
        /// <summary>
        /// Carteras de clientes.
        /// </summary>
        /// -----------------------------------------------------------------------------------------------------------
        DbSet<Portfolio> Portfolios { get; }

        /// -----------------------------------------------------------------------------------------------------------
        /// <summary>
        /// Posiciones de cartera.
        /// </summary>
        /// -----------------------------------------------------------------------------------------------------------
        DbSet<PortfolioPosition> PortfolioPositions { get; }

        /// -----------------------------------------------------------------------------------------------------------
        /// <summary>
        /// Órdenes registradas.
        /// </summary>
        /// -----------------------------------------------------------------------------------------------------------
        DbSet<Order> Orders { get; }

        /// -----------------------------------------------------------------------------------------------------------
        /// <summary>
        /// Alertas de precio.
        /// </summary>
        /// -----------------------------------------------------------------------------------------------------------
        DbSet<PriceAlert> PriceAlerts { get; }

        /// <summary>Notificaciones persistidas de alertas.</summary>
        DbSet<PriceAlertNotification> PriceAlertNotifications { get; }

        /// -----------------------------------------------------------------------------------------------------------
        /// <summary>
        /// Persiste los cambios pendientes.
        /// </summary>
        /// <param name="cancellationToken">Cancelación.</param>
        /// <returns>Número de entidades afectadas.</returns>
        /// -----------------------------------------------------------------------------------------------------------
        Task<int> SaveChangesAsync(CancellationToken cancellationToken = default);
    }
}
